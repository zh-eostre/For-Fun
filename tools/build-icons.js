// Builds js/icons.js from the SVGs in art/icons (one path each, on a 512×512 grid), so the page can draw them inline
// in any colour without loading files. Run after adding or changing an icon:  node tools/build-icons.js
const fs=require('fs'),path=require('path');
const root=path.join(__dirname,'..'),dir=path.join(root,'art/icons');
const icons={};
for(const f of fs.readdirSync(dir).filter(f=>f.endsWith('.svg')).sort()){
  const d=fs.readFileSync(path.join(dir,f),'utf8').match(/<path\s+d="([^"]+)"/);
  if(!d)throw new Error('no path in '+f);
  icons[f.slice(0,-4)]=d[1];
}
const out=`/* ---------- icons (generated by tools/build-icons.js from art/icons; see art/CREDITS.md) ---------- */
const ICONS=${JSON.stringify(icons,null,0).replace(/","/g,'",\n"')};
const ico=(k,cls='')=>ICONS[k]?\`<svg class="ico \${cls}" viewBox="0 0 512 512" aria-hidden="true"><path d="\${ICONS[k]}"/></svg>\`:'';
const sprite=(k,cls='')=>\`<img class="sprite \${cls}" src="art/monsters/\${k}.png" alt="" draggable="false">\`;
`;
fs.writeFileSync(path.join(root,'js/icons.js'),out);
console.log(Object.keys(icons).length+' icons → js/icons.js');
