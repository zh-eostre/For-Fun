// Builds js/names.js from Chinese-Names-Corpus (https://github.com/wainshine/Chinese-Names-Corpus, Apache-2.0).
// The full corpora are ~30MB, too big for the page, so this keeps a few thousand common entries.
// Run once with `node tools/build-names.js`; the downloads are cached in tools/.corpus (not committed).
// Only name parts are kept (surnames and given names separately), so no full name from the corpus is reproduced.
const fs=require('fs'),path=require('path');
const SRC='https://raw.githubusercontent.com/wainshine/Chinese-Names-Corpus/master/';
const FILES={cn:'Chinese_Names_Corpus/Chinese_Names_Corpus_Gender（120W）.txt',
  en:'English_Names_Corpus/English_Cn_Name_Corpus_Gender（48W）.txt',jp:'Japanese_Names_Corpus/Japanese_Names_Corpus（18W）.txt'};
const cache=path.join(__dirname,'.corpus'),out=path.join(__dirname,'..','js','names.js');

async function load(k){
  const f=path.join(cache,k+'.txt');
  if(!fs.existsSync(f)){
    fs.mkdirSync(cache,{recursive:true});
    const r=await fetch(SRC+encodeURI(FILES[k]));if(!r.ok)throw new Error(FILES[k]+': '+r.status);
    fs.writeFileSync(f,Buffer.from(await r.arrayBuffer()));
  }
  return fs.readFileSync(f,'utf8').replace(/^﻿/,'').split(/\r?\n/).map(l=>l.trim()).filter(Boolean);
}
const count=a=>{const m=new Map;for(const x of a)m.set(x,(m.get(x)||0)+1);return m};
const top=(m,n)=>[...m].sort((a,b)=>b[1]-a[1]||(a[0]<b[0]?-1:1)).slice(0,n).map(e=>e[0]);
// seeded shuffle so the output only changes when the corpus does
let seed=20261006;const rnd=()=>(seed=(seed*1103515245+12345)%2147483648)/2147483648;
const sample=(a,n)=>{a=[...a].sort();for(let i=a.length-1;i>0;i--){const j=Math.floor(rnd()*(i+1));[a[i],a[j]]=[a[j],a[i]]}return a.slice(0,n)};

(async()=>{
  // Chinese: "姓名,性别" full names. Surnames by frequency; given names kept if common and almost always male
  const cn=(await load('cn')).filter(l=>/^[一-鿿]{2,3},(男|女|未知)$/.test(l)).map(l=>l.split(','));
  const SUR=top(count(cn.filter(([n])=>n.length===3).map(([n])=>n[0])),100),sur=new Set(SUR);
  const m=new Map,f=new Map,add=(c,g)=>c.set(g,(c.get(g)||0)+1);
  for(const [n,s] of cn)if(sur.has(n[0])&&s!=='未知')add(s==='男'?m:f,n.slice(1));
  const male=g=>m.get(g)/(m.get(g)+(f.get(g)||0))>=.92;
  const give=len=>top(new Map([...m].filter(([g,v])=>g.length===len&&v>=25&&male(g)&&g[0]!==g[1])),len===2?4000:150);
  const G2=give(2),G1=give(1);
  // characters common enough in Chinese names to read naturally (used to screen the Japanese entries)
  const common=new Set(top(count(cn.flatMap(([n])=>[...n])),3500));

  // transliterated Western names ("中文|English|M/F"): the English pairing and first/last split are unreliable,
  // so only surname-like entries are used, written in the characters translators use most and without female endings
  const en=(await load('en')).map(l=>l.split('|')).filter(x=>x.length===3);
  const chars=new Set(top(count(en.flatMap(x=>[...x[0]])),150));
  const EU=sample(new Set(en.filter(([c,,s])=>s==='M'&&/^[一-鿿]{3,4}$/.test(c)&&[...c].every(ch=>chars.has(ch))
    &&!/[娃娅娜丽莉妮莎芭婭]/.test(c)).map(x=>x[0])),1500);

  // Japanese full names: four characters split 2+2; given names with a typically male ending
  const jp=(await load('jp')).filter(l=>/^[一-鿿]{4}$/.test(l)&&[...l].every(c=>common.has(c)));
  const JS=top(count(jp.map(j=>j.slice(0,2))),150);
  const JG=top(new Map([...count(jp.map(j=>j.slice(2)))].filter(([g,v])=>v>=4&&/[郎夫雄男彦也介太平树人一二三俊博明浩弘治司史之信昭隆宏和辉翔斗大哉吾辅亮诚健刚真悟裕]$/.test(g))),300);

  const line=(k,a)=>`const ${k}=${JSON.stringify(a.join(' '))}.split(' ');\n`;
  fs.writeFileSync(out,`/* generated by tools/build-names.js — do not edit by hand.
   name parts from Chinese-Names-Corpus by wainshine (https://github.com/wainshine/Chinese-Names-Corpus), Apache-2.0 */
`+line('CN_SUR',SUR)+line('CN_GIV2',G2)+line('CN_GIV1',G1)+line('EU_SUR',EU)+line('JP_SUR',JS)+line('JP_GIV',JG));
  console.log(`CN surnames ${SUR.length}, given ${G2.length}+${G1.length}; EU surnames ${EU.length}; JP ${JS.length}/${JG.length}; ${(fs.statSync(out).size/1024).toFixed(0)}KB`);
})();
